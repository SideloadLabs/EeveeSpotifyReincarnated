"""Current target identity and explicit production source ownership."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
import os
PROFILE_PATH = ROOT / os.environ.get("PIXIE_TARGET", "targets/spotify-9.2.0.json")
PROFILE = json.loads(PROFILE_PATH.read_text())


def native_address(name):
    return int(PROFILE["native"][name], 16)


def native_bytes(name):
    return bytes.fromhex(PROFILE["native"][name])


def resolve_source(name):
    """Require a single declared file, including after a directory move."""
    direct = ROOT / "src" / name
    if direct.is_file():
        return direct
    matches = [p for p in (ROOT / "src").rglob("*")
               if p.is_file() and p.name == name]
    if len(matches) != 1:
        raise ValueError(f"Expected one production source for {name}: {matches}")
    return matches[0]


def source_group(name):
    result = []
    for member in PROFILE["groups"][name]:
        entries = source_group(member[1:]) if member.startswith("@") else [resolve_source(member)]
        for entry in entries:
            if entry not in result:
                result.append(entry)
    return result


def companion_sources():
    return [resolve_source(name) for name in PROFILE["companion_sources"]]


def include_directories():
    return sorted({ROOT / "src", *(p.parent for p in (ROOT / "src").rglob("*.h"))})


def validate_sources():
    sources = companion_sources()
    if len(sources) != len(set(sources)):
        raise ValueError("Duplicate production translation unit")
    actual = {path for path in (ROOT / "src").rglob("*")
              if path.is_file() and path.suffix in {".m", ".c"}}
    if actual != set(sources):
        raise ValueError(f"Undeclared production files: {sorted(actual - set(sources))}")
    headers = [path.name for path in (ROOT / "src").rglob("*.h")]
    if len(headers) != len(set(headers)):
        raise ValueError("Ambiguous production header basename")
    for name in PROFILE["groups"]:
        source_group(name)
    return sources


def target_header():
    def array(value):
        return ",".join(f"0x{byte:02x}" for byte in bytes.fromhex(value))
    native = PROFILE["native"]
    return ("#pragma once\n// Generated by tools/generate_target.py; edit the target profile instead.\n"
            "#include <stdint.h>\n"
            f'#define SAP_SPOTIFY_VERSION "{PROFILE["spotify_version"]}"\n'
            f'#define SAP_SPOTIFY_UUID_HEX "{PROFILE["uuid"]}"\n'
            f'#define SAP_SPOTIFY_UUID_BYTES {{{array(PROFILE["uuid"])}}}\n'
            f'#define SAP_SETTER_ORIGINAL_BYTES {{{array(native["setter_original"])}}}\n'
            + "".join(f"#define SAP_TARGET_{key.upper()} UINT64_C({native[key]})\n"
                      for key in ["setter", "manager_vtable", "provider", "render_callback"]))
