"""Keep offline lyrics reads available without registering lyrics as a download resource."""
import struct

from patch_native_restrictions import branch, layout

BASE = 0x100000000
UUID = bytes.fromhex("b49e75781d8635d38bb57daf68fed8a8")
WINDOW_ADDRESS = 0x108715788
BRANCH_ADDRESS = 0x1087157A0
SKIP_ADDRESS = 0x108715918
ORIGINAL = bytes.fromhex("280c03f008410491080140f9740e00f9886a68381f050071c10b0054000080d203e3ef96271a6f94")
SKIP_HEAD = bytes.fromhex("e00319aaed9f8294090740f9a80304d1f40319aa")
BRANCH_INDEX = BRANCH_ADDRESS - WINDOW_ADDRESS
PATCHED = ORIGINAL[:BRANCH_INDEX] + struct.pack("<I", branch(BRANCH_ADDRESS, SKIP_ADDRESS)) + ORIGINAL[BRANCH_INDEX+4:]


def patch(data):
    _, _, segments, uuid = layout(data)
    if uuid != UUID:
        return data, {"applied": False, "reason": "unverified Spotify executable"}
    _, vm, _, fileoff, filesize, protection = next(s for s in segments if s[0] == b"__TEXT")
    if not vm <= WINDOW_ADDRESS or SKIP_ADDRESS + len(SKIP_HEAD) > vm + filesize or protection & 5 != 5:
        raise ValueError("Offline lyrics registration guard is outside executable __TEXT")
    window = fileoff + WINDOW_ADDRESS - vm
    destination = fileoff + SKIP_ADDRESS - vm
    if data[window:window+len(ORIGINAL)] != ORIGINAL or data[destination:destination+len(SKIP_HEAD)] != SKIP_HEAD:
        raise ValueError("Unexpected offline lyrics registration branch or skip target")
    offset = window + BRANCH_INDEX
    replacement = PATCHED[BRANCH_INDEX:BRANCH_INDEX+4]
    return data[:offset] + replacement + data[offset+4:], {
        "applied": True, "uuid": UUID.hex(), "file_offset": offset,
        "entry": hex(BRANCH_ADDRESS), "destination": hex(SKIP_ADDRESS),
        "old_bytes": ORIGINAL[BRANCH_INDEX:BRANCH_INDEX+4].hex(), "new_bytes": replacement.hex(),
    }


def guard_header():
    def c_bytes(data):
        return ",".join(f"0x{x:02x}" for x in data)

    return (
        "#pragma once\n#include <stdint.h>\n"
        "// Generated by patch_lyrics_plugin_registration.py.\n"
        f"static const uint8_t SAPLyricsRegistrationUUID[]={{{c_bytes(UUID)}}};\n"
        f"static const uintptr_t SAPLyricsRegistrationOffset=0x{WINDOW_ADDRESS-BASE:x};\n"
        f"static const uint8_t SAPLyricsRegistrationGuard[]={{{c_bytes(PATCHED)}}};\n"
        f"static const uintptr_t SAPLyricsRegistrationSkipOffset=0x{SKIP_ADDRESS-BASE:x};\n"
        f"static const uint8_t SAPLyricsRegistrationSkipHead[]={{{c_bytes(SKIP_HEAD)}}};\n"
    )
